// Builds the search box's static embedding model from Model2Vec potion-base-2M (MIT, Minish Lab), pinned to one
// revision and checked against SHA-256s. The vocabulary is pruned to Latin-script tokens and the table quantised
// per row to int8, then written to public/models/search/ (committed, so builds never depend on Hugging Face):
//   potion-2m-<sha8>.bin   "M2V1", rows, dim (uint32 LE), float32 scales[rows], int8 data[rows × dim]
//   vocab-<sha8>.txt       one token per line; line n is row n
// and src/search/manifest.generated.ts with their names, sizes and hashes. Idempotent: does nothing when the files
// already match the manifest. SEARCH_MODEL_DIR=<dir> reuses a local copy of the two source files.
import { createHash } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = join(root, 'public/models/search');
const MANIFEST = join(root, 'src/search/manifest.generated.ts');
const REPO = 'minishlab/potion-base-2M';
const REV = '389b9f64be5aa4ae7a6bc6fe95ef20ce485ae5da';
const SOURCES = {
  'model.safetensors': 'f95ffde02ad06f63ae38eb9d400038cd5ccaf8411ec3cb650c6025113f96cbb8',
  'tokenizer.json': 'e67e803f624fb4d67dea1c730d06e1067e1b14d830e2c2202569e3ef0f70bb50',
};

const sha256 = (buf) => createHash('sha256').update(buf).digest('hex');

async function current() {
  if (!existsSync(MANIFEST)) return false;
  const text = await readFile(MANIFEST, 'utf8');
  for (const [, file, hash] of text.matchAll(/file: '([^']+)'[^}]*sha256: '([0-9a-f]+)'/g)) {
    const buf = await readFile(join(OUT, file)).catch(() => null);
    if (!buf || sha256(buf) !== hash) return false;
  }
  return text.includes(REV);
}

async function source(name) {
  const local = process.env.SEARCH_MODEL_DIR && join(process.env.SEARCH_MODEL_DIR, name);
  const buf = local ? await readFile(local) : Buffer.from(await (await fetch(`https://huggingface.co/${REPO}/resolve/${REV}/${name}`)).arrayBuffer());
  if (sha256(buf) !== SOURCES[name]) throw new Error(`vendor-search: ${name} doesn't match its pinned SHA-256`);
  return buf;
}

if (await current()) process.exit(0);

const st = await source('model.safetensors');
const tok = JSON.parse((await source('tokenizer.json')).toString('utf8'));
const hlen = Number(st.readBigUInt64LE(0));
const header = JSON.parse(st.subarray(8, 8 + hlen).toString('utf8'));
const [, meta] = Object.entries(header).find(([k]) => k !== '__metadata__');
const [rows, dim] = meta.shape;
const raw = st.subarray(8 + hlen + meta.data_offsets[0], 8 + hlen + meta.data_offsets[1]);
const table = new Float32Array(raw.buffer.slice(raw.byteOffset, raw.byteOffset + raw.byteLength));

// keep Latin-script tokens (plus digits, punctuation and the special tokens); [unusedN] and other scripts go
const byId = [];
for (const [token, id] of Object.entries(tok.model.vocab)) byId[id] = token;
const keep = byId
  .map((t, id) => ({ t, id }))
  .filter(({ t }) => !/^\[unused\d+\]$/.test(t) && /^[\p{Script=Latin}\p{Script=Common}\p{Script=Inherited}]+$/u.test(t.replace(/^##/, '')));

const head = Buffer.alloc(12);
head.write('M2V1', 0, 'ascii');
head.writeUInt32LE(keep.length, 4);
head.writeUInt32LE(dim, 8);
const scales = new Float32Array(keep.length);
const data = new Int8Array(keep.length * dim);
keep.forEach(({ id }, r) => {
  let max = 0;
  for (let c = 0; c < dim; c++) max = Math.max(max, Math.abs(table[id * dim + c]));
  const s = max / 127 || 1;
  scales[r] = s;
  for (let c = 0; c < dim; c++) data[r * dim + c] = Math.round(table[id * dim + c] / s);
});
const bin = Buffer.concat([head, Buffer.from(scales.buffer), Buffer.from(data.buffer)]);
const vocab = Buffer.from(keep.map(({ t }) => t).join('\n'), 'utf8');
const files = [
  { key: 'model', file: `potion-2m-${sha256(bin).slice(0, 8)}.bin`, buf: bin },
  { key: 'vocab', file: `vocab-${sha256(vocab).slice(0, 8)}.txt`, buf: vocab },
];

await mkdir(OUT, { recursive: true });
for (const old of await readdir(OUT)) if (!files.some((f) => f.file === old)) await rm(join(OUT, old));
for (const f of files) await writeFile(join(OUT, f.file), f.buf);

const lines = files.map((f) => `  ${f.key}: { file: '${f.file}', bytes: ${f.buf.length}, sha256: '${sha256(f.buf)}' },`);
await writeFile(
  MANIFEST,
  `// Generated by scripts/vendor-search.mjs; do not edit.
// ${REPO} at revision ${REV} (MIT), Latin vocabulary, int8 per row: ${keep.length} of ${rows} rows × ${dim}.
export const SEARCH_MODEL = {
  repo: '${REPO}',
  revision: '${REV}',
  rows: ${keep.length},
  dim: ${dim},
${lines.join('\n')}
} as const;
`,
);
console.log(`vendor-search: ${keep.length}/${rows} rows × ${dim}, ${files.map((f) => `${f.file} ${f.buf.length} B`).join(', ')}`);
